/**
 * Helper to retrieve dynamic insights for a given capability serviceId.
 * Falls back cleanly to any custom items or default catalog.
 */
export function getCapabilityInsights(serviceId, existingInsights) {
  // If the serviceId exists in the dynamic verified map, use it
  if (CAPABILITY_INSIGHTS_MAP[serviceId]) {
    return CAPABILITY_INSIGHTS_MAP[serviceId];
  }
  
  // Otherwise, use existing items or fallback
  if (existingInsights && existingInsights.items && existingInsights.items.length > 0) {
    return existingInsights.items;
  }

  return CAPABILITY_INSIGHTS_MAP["generative-ai"];
}
